# print() fonskiyonu sıklıkla değişkenleri yazdırmak için kullanılır.
x = "Python is awesome"
print(x)
print()

# Birden fazla değişkeni yazdırmak için onları virgülle ayırabilirsiniz.
x = "Python"
y = "is"
z = "awesome"
print(x, y , z)
print()

# Ayrıca + operatörünü de kullanabilirsiniz.
x = "Python "
y = "is "
z = "awesome"
print(x + y + z)
print()

# Sayılar için + operatörü matematik operatörü olarak çalışır.
