# Hepsini büyük harf yapma
a = "Hello, World!"
print(a.upper())
print()

# Hepsini küçük harf yapma
a = "Hello, World!"
print(a.lower())
print()

# Baştaki ve sondaki boşlukları silme
a = "  Hello, World!  "
print(a.strip())
print()

# Stringleri yer değiştirme
a = "Hello, World!"
print(a.replace("H", "J"))
print()

# Stringleri ayırma
a = "Hello, World!"
print(a.split(","))
print()

# Stringleri birleştirme
a = "Hello"
b = "World"
c = a + b
print(c)
print()
