# Access Items
thislist = ["apple", "banana", "cherry"]
print(thislist[1])
print()

# Negative Indexing
thislist = ["apple", "banana", "cherry"]
print(thislist[-1])
print()

# Range of Indexes
thislist = ["apple", "banana", "cherry", "orange", "kiwi", "melon", "mango"]
print(thislist[2:5])
print(thislist[:4])
print(thislist[2:])
print()

# Range of Negative Indexes
thislist = ["apple", "banana", "cherry", "orange", "kiwi", "melon", "mango"]
print(thislist[-4:-1])
print(thislist[-4:])
print()

# Check if Item Exits
thislist = ["apple", "banana", "cherry"]
if "apple" in thislist:
    print("Yes, 'apple' is in the fruits list")
print()

